"""Verify WCAG 2.2 contrast for every ProxyFlow colour-role pairing and write
design/tokens/contrast-report.md. Exit code 1 if any required pair fails.

Thresholds: 4.5:1 for normal text and icons that carry meaning (AA 1.4.3),
3:1 for large text (>= 18sp / 14sp bold) and non-text UI boundaries (AA 1.4.11).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "tokens/proxyflow.tokens.json"
REPORT = ROOT / "tokens/contrast-report.md"

# (foreground role, background role, minimum ratio, usage)
PAIRS = [
    ("onBackground", "background", 4.5, "body text on screen background"),
    ("onSurface", "surface", 4.5, "text on cards / sheets"),
    ("onSurfaceVariant", "surface", 4.5, "secondary text on cards"),
    ("onSurfaceVariant", "background", 4.5, "secondary text on background"),
    ("onSurfaceVariant", "surfaceVariant", 4.5, "text on chips / tonal fields"),
    ("primary", "background", 4.5, "links, text buttons, active icons"),
    ("primary", "surface", 4.5, "text buttons on cards"),
    ("onPrimary", "primary", 4.5, "label on filled primary button"),
    ("onPrimaryContainer", "primaryContainer", 4.5, "text on tonal primary container"),
    ("onSecondary", "secondary", 4.5, "label on navy button"),
    ("onSecondaryContainer", "secondaryContainer", 4.5, "text on secondary container"),
    ("error", "background", 4.5, "error text"),
    ("error", "surface", 4.5, "field error text"),
    ("onError", "error", 4.5, "label on destructive button"),
    ("onErrorContainer", "errorContainer", 4.5, "error banner text"),
    ("warning", "background", 4.5, "reconnecting status text"),
    ("onWarningContainer", "warningContainer", 4.5, "warning banner text"),
    ("onAccentFill", "accentFill", 4.5, "label/icon on big connect button"),
    ("statusConnected", "background", 4.5, "'Connected' status text"),
    ("statusTransition", "background", 4.5, "'Connecting/Reconnecting' status text"),
    ("statusOff", "background", 4.5, "'Disconnected' status text"),
    ("statusError", "background", 4.5, "'Error' status text"),
    ("outline", "surface", 3.0, "text-field border, toggle track (non-text)"),
    ("outline", "background", 3.0, "outlined card border (non-text)"),
]

# Informational pairs: documented, not required.
INFO = [
    ("accentFill", "background", "brand teal fill against background (button identified by its label; add outline)"),
    ("brand.teal", "#FFFFFF", "brand teal under white text — why white-on-teal is NOT used"),
]


def lum(h: str) -> float:
    h = h.lstrip("#")
    rgb = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    lin = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in rgb]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def ratio(a: str, b: str) -> float:
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def resolve(tokens: dict, value: str) -> str:
    m = re.fullmatch(r"\{([\w.]+)\}", value)
    if not m:
        return value
    node = tokens
    for part in m.group(1).split("."):
        node = node[part]
    return resolve(tokens, node["$value"])


def color(tokens, scheme, role):
    if role.startswith("#"):
        return role
    if role.startswith("brand."):
        return resolve(tokens, "{" + role + "}")
    return resolve(tokens, tokens["color"][scheme][role]["$value"])


def main() -> int:
    tokens = json.loads(TOKENS.read_text())
    lines = ["# Contrast report (generated)", "",
             "Generated by `design/tools/check_contrast.py` from `proxyflow.tokens.json`. "
             "Required: 4.5:1 text/meaningful icons, 3:1 large text and UI boundaries (WCAG 2.2 AA).", ""]
    failed = 0
    for scheme in ("light", "dark"):
        lines += [f"## {scheme.title()} theme", "", "| Foreground | Background | Ratio | Min | Result | Usage |",
                  "|---|---|---|---|---|---|"]
        for fg, bg, need, use in PAIRS:
            f, b = color(tokens, scheme, fg), color(tokens, scheme, bg)
            r = ratio(f, b)
            ok = r >= need
            failed += not ok
            lines.append(f"| `{fg}` {f} | `{bg}` {b} | {r:.2f}:1 | {need}:1 | {'PASS' if ok else '**FAIL**'} | {use} |")
        lines += ["", "Informational:", ""]
        for fg, bg, note in INFO:
            f, b = color(tokens, scheme, fg), color(tokens, scheme, bg)
            lines.append(f"- `{fg}` {f} on `{bg}` {b}: {ratio(f, b):.2f}:1 — {note}")
        lines.append("")
    lines.append(f"**Result: {'all required pairs pass' if not failed else f'{failed} required pair(s) fail'}.**")
    REPORT.write_text("\n".join(lines) + "\n")
    print(f"{'OK' if not failed else 'FAIL'}: {failed} failing pair(s); wrote {REPORT}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
