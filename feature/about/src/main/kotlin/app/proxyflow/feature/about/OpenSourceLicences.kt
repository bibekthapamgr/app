/** A licence the notices name, with the asset that holds its full text. */
data class OpenSourceLicence(val id: String, val title: String, val textAsset: String)

/** A library the app ships, at the version it ships, under [licence] (an [OpenSourceLicence.id]). */
data class OpenSourceLibrary(val name: String, val version: String, val licence: String)

/**
 * The open-source notices (M9): every library of the release build with the licence its POM declares, and the Go
 * modules linked into the engine — generated by scripts/licences.py, which CI checks against the release build — and
 * the full text of each licence, shipped with the app.
 */
data class OpenSourceNotices(val licences: List<OpenSourceLicence>, val libraries: List<OpenSourceLibrary>) {
    fun librariesUnder(id: String): List<OpenSourceLibrary> = libraries.filter { it.licence == id }

    companion object {
        const val ASSET = "open_source_licences.json"

        /** @throws JSONException when [json] is not the notices' format. */
        fun parse(json: String): OpenSourceNotices {
            val root = JSONObject(json)
            val licences = root.getJSONObject("licences")
            val libraries = root.getJSONArray("libraries")
            return OpenSourceNotices(
                licences = licences.keys().asSequence().map { id ->
                    val licence = licences.getJSONObject(id)
                    OpenSourceLicence(id, licence.getString("title"), licence.getString("text"))
                }.toList(),
                libraries = (0 until libraries.length()).map { i ->
                    val library = libraries.getJSONObject(i)
                    OpenSourceLibrary(library.getString("name"), library.getString("version"), library.getString("licence"))
                },
            )
        }

        /** The notices the app ships; null when they can't be read (never expected: they are part of the APK). */
        fun read(context: Context): OpenSourceNotices? = try {
            context.assets.open(ASSET).bufferedReader().use { parse(it.readText()) }
        } catch (e: IOException) {
            null
        } catch (e: JSONException) {
            null
        }

        /** [licence]'s full text as the app ships it; null when it can't be read. */
        fun text(context: Context, licence: OpenSourceLicence): String? = try {
            context.assets.open(licence.textAsset).bufferedReader().use { it.readText() }
        } catch (e: IOException) {
            null
        }
    }
}

@Composable
internal fun LicencesRoute(onBack: () -> Unit, onOpenLicence: (String) -> Unit) {
    val context = LocalContext.current
    // A few kilobytes from the APK's assets, once.
    val notices = remember(context) { OpenSourceNotices.read(context) }
    LicencesScreen(notices, onBack = onBack, onOpenLicence = onOpenLicence)
}

/** Every library ProxyFlow ships, grouped by its licence, each licence's full text one tap away. */
@Composable
fun LicencesScreen(notices: OpenSourceNotices?, onBack: () -> Unit, onOpenLicence: (String) -> Unit, modifier: Modifier = Modifier) {
    Scaffold(
        modifier = modifier,
        topBar = { PfTopAppBar(title = stringResource(R.string.licences_title), onBack = onBack) },
    ) { padding ->
        if (notices == null) {
            PfErrorState(
                title = stringResource(R.string.licences_unreadable_title),
                body = stringResource(R.string.licences_unreadable_body),
                modifier = Modifier.padding(padding),
            )
            return@Scaffold
        }
        LazyColumn(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .consumeWindowInsets(padding),
            contentPadding = PaddingValues(horizontal = Spacing.screenGutter, vertical = Spacing.md),
            verticalArrangement = Arrangement.spacedBy(Spacing.sm),
        ) {
            item(key = "lead") { Text(stringResource(R.string.licences_lead), style = MaterialTheme.typography.bodyMedium) }
            for (licence in notices.licences) {
                val libraries = notices.librariesUnder(licence.id)
                item(key = "licence ${licence.id}") {
                    Column(Modifier.padding(top = Spacing.md), verticalArrangement = Arrangement.spacedBy(Spacing.xs)) {
                        Text(
                            licence.title,
                            style = MaterialTheme.typography.titleMedium,
                            color = MaterialTheme.colorScheme.primary,
                            modifier = Modifier.semantics { heading() },
                        )
                        Text(
                            pluralStringResource(R.plurals.licences_count, libraries.size, libraries.size),
                            style = MaterialTheme.typography.bodySmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                        )
                        PfTextButton(text = stringResource(R.string.licences_read, licence.title), onClick = { onOpenLicence(licence.id) })
                    }
                }
                items(libraries, key = { "library ${licence.id} ${it.name}" }) { library ->
                    Column {
                        Text(library.name, style = MaterialTheme.typography.bodyMedium)
                        Text(library.version, style = MonoSmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                    }
                }
            }
        }
    }
}

@Composable
internal fun LicenceTextRoute(id: String, onBack: () -> Unit) {
    val context = LocalContext.current
    val shown = remember(context, id) {
        OpenSourceNotices.read(context)?.licences?.firstOrNull { it.id == id }?.let { it to OpenSourceNotices.text(context, it) }
    }
    LicenceTextScreen(title = shown?.first?.title, text = shown?.second, onBack = onBack)
}

/**
 * A licence's full text. The files wrap their lines for a wide screen; here each paragraph flows to the phone's width,
 * the words unchanged.
 */
@Composable
fun LicenceTextScreen(title: String?, text: String?, onBack: () -> Unit, modifier: Modifier = Modifier) {
    val paragraphs = remember(text) { text?.let(::paragraphsOf) }
    Scaffold(
        modifier = modifier,
        topBar = { PfTopAppBar(title = title ?: stringResource(R.string.licences_title), onBack = onBack) },
    ) { padding ->
        if (title == null || paragraphs == null) {
            PfErrorState(
                title = stringResource(R.string.licences_unreadable_title),
                body = stringResource(R.string.licences_unreadable_body),
                modifier = Modifier.padding(padding),
            )
            return@Scaffold
        }
        LazyColumn(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .consumeWindowInsets(padding),
            contentPadding = PaddingValues(horizontal = Spacing.screenGutter, vertical = Spacing.md),
            verticalArrangement = Arrangement.spacedBy(Spacing.sm),
        ) {
            item(key = "title") {
                Text(title, style = MaterialTheme.typography.titleMedium, modifier = Modifier.semantics { heading() })
            }
            items(paragraphs) { paragraph -> Text(paragraph, style = MaterialTheme.typography.bodyMedium) }
        }
    }
}

/** [text]'s paragraphs (blank-line separated), each one's lines joined. */
internal fun paragraphsOf(text: String): List<String> = text.split(Regex("""\n[ \t]*\n""")).map { paragraph ->
    paragraph.lines().joinToString(" ") { it.trim() }.trim()
}.filter { it.isNotEmpty() }
