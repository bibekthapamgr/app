#!/usr/bin/env python3
"""Starts the next release (M12, docs/m12/maintenance-runbook.md §4): one command that makes every place that names
the version agree, so a release cannot be built with a changelog, a history row or a privacy policy that still name
the last one.

    scripts/release/bump_version.py 1.0.1            # versionCode goes up by one; versionName as given

What it changes:
  - app/build.gradle.kts: versionCode + 1, versionName;
  - CHANGELOG.md: a new section "## [<name> (<code>)] — not yet on Google Play" under [Unreleased], taking the entries
    [Unreleased] held (the owner edits the words; check_release_ready.py refuses an empty section);
  - docs/m12/release-history.md: a new first row with "pending" in the commit and run columns;
  - docs/m9/privacy-policy.md: regenerated by scripts/privacy_policy.py (its version line);
  - the data-behaviour lock is left alone: if the release changed what the app keeps or sends, check_data_behavior.py
    fails until the policy review (docs/m12/policy-review.md) and --update.
Nothing is committed; the owner reviews the diff. The version name must be newer than the current one (semantic
versioning, MAJOR.MINOR.PATCH).
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys

ROOT = os.environ.get("PROXYFLOW_ROOT") or os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))


def path(rel: str) -> str:
    return os.path.join(ROOT, rel)


def read(rel: str) -> str:
    with open(path(rel), encoding="utf-8") as f:
        return f.read()


def write(rel: str, text: str) -> None:
    with open(path(rel), "w", encoding="utf-8") as f:
        f.write(text)


def parse(name: str) -> tuple[int, int, int]:
    m = re.fullmatch(r"(\d+)\.(\d+)\.(\d+)", name)
    if not m:
        raise SystemExit(f"not a MAJOR.MINOR.PATCH version: {name}")
    return tuple(int(x) for x in m.groups())  # type: ignore[return-value]


def bump(name: str) -> tuple[str, int]:
    gradle = read("app/build.gradle.kts")
    old_name = re.search(r'versionName\s*=\s*"([^"]+)"', gradle).group(1)
    old_code = int(re.search(r"versionCode\s*=\s*(\d+)", gradle).group(1))
    if parse(name) <= parse(old_name):
        raise SystemExit(f"{name} is not newer than the current {old_name}")
    code = old_code + 1
    gradle = re.sub(r"versionCode\s*=\s*\d+", f"versionCode = {code}", gradle, count=1)
    gradle = re.sub(r'versionName\s*=\s*"[^"]+"', f'versionName = "{name}"', gradle, count=1)
    write("app/build.gradle.kts", gradle)

    changelog = read("CHANGELOG.md")
    label = f"{name} ({code})"
    if f"## [{label}]" in changelog:
        raise SystemExit(f"CHANGELOG.md already has a section for {label}")
    m = re.search(r"^## \[Unreleased\]\n(.*?)(?=^## \[|\Z)", changelog, re.M | re.S)
    if not m:
        raise SystemExit("CHANGELOG.md has no [Unreleased] section")
    held = m.group(1).strip("\n")
    section = f"## [Unreleased]\n\n## [{label}] — not yet on Google Play\n\n{held}\n\n" if held else f"## [Unreleased]\n\n## [{label}] — not yet on Google Play\n\n### Changed\n- (what this release changes)\n\n"
    changelog = changelog[: m.start()] + section + changelog[m.end() :]
    changelog = re.sub(r"^\[Unreleased\]: .*$", f"[Unreleased]: https://github.com/bibekthapamgr/app/compare/v{name}...HEAD\n[{label}]: https://github.com/bibekthapamgr/app/releases/tag/v{name}", changelog, count=1, flags=re.M)
    write("CHANGELOG.md", changelog)

    history = read("docs/m12/release-history.md")
    header = re.search(r"^\|---\|.*\|\n", history, re.M)
    if not header:
        raise SystemExit("docs/m12/release-history.md: no table")
    row = f"| {label} | pending | pending | pending | pending | pending | — | — |\n"
    history = history[: header.end()] + row + history[header.end() :]
    write("docs/m12/release-history.md", history)

    subprocess.run([sys.executable, path("scripts/privacy_policy.py"), "--out", path("docs/m9/privacy-policy.md")], check=True, cwd=ROOT)
    return name, code


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("name", help="the new versionName, MAJOR.MINOR.PATCH")
    args = parser.parse_args(argv)
    name, code = bump(args.name)
    print(f"{name} ({code}): app/build.gradle.kts, CHANGELOG.md (edit the new section), docs/m12/release-history.md (a pending row), docs/m9/privacy-policy.md regenerated; now: the What's new in docs/m11/store-listing.md §7, then scripts/release/check_release_ready.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
